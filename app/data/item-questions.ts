import type { AnswerWeights, Question, QuestionOption, QuizRoute } from './types';
import { itemImage } from './item-images';

type SceneItem = { id: string; title: string };

const item = (
  id: string,
  title: string,
  weights: AnswerWeights,
  description = 'Pokopia 道具图鉴',
  sceneItems?: SceneItem[],
): QuestionOption => ({
  id,
  title,
  description,
  image: itemImage(id),
  imageAlt: `${title}的 Pokopia 道具图`,
  sceneItems: sceneItems?.map((sceneItem) => ({
    image: itemImage(sceneItem.id),
    imageAlt: `${sceneItem.title}的 Pokopia 道具图`,
    title: sceneItem.title,
  })),
  ...weights,
});

const one = (
  id: string,
  eyebrow: string,
  prompt: string,
  hint: string,
  options: QuestionOption[],
  requiresAnyRoute?: QuizRoute[],
): Question => ({
  id,
  eyebrow,
  prompt,
  hint,
  minSelections: 1,
  maxSelections: 1,
  presentation: 'items',
  options: [
    ...options,
    {
      id: `${id}-other`,
      title: '其他 / 都不太想',
      description: '现有选项没有说中我，这题不计入图鉴标签。',
      routeTags: id === 'island-errand'
        ? ['creative', 'craft', 'explore', 'food', 'home', 'nature', 'social']
        : undefined,
    },
  ],
  phase: requiresAnyRoute ? 'branch' : 'core',
  requiresAnyRoute,
});

const route = (option: QuestionOption, ...routeTags: QuizRoute[]): QuestionOption => ({
  ...option,
  routeTags,
});

